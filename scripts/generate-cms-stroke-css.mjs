/**
 * Generates src/styles/base/cms-stroke.css.
 *
 * The section stylesheets recolour icons with `fill` (`.box:hover .icon svg path { fill:#fff }`). An outline icon
 * (fill="none" + stroke) uploaded in the admin panel gets the class `cms-stroke` from sanitizeSvg(), and needs the same
 * colour on its `stroke`. For every `… svg <shape> { fill:X }` rule this writes `… svg <shape>.cms-stroke { stroke:X }`
 * (inside the same @media / @supports), so outline icons follow every existing hover / active / theme colour.
 *
 * Run after changing icon colours in styles/sections:   node scripts/generate-cms-stroke-css.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const STYLES = path.join(process.cwd(), 'src/styles');
const OUT = path.join(STYLES, 'base/cms-stroke.css');
const SHAPE = /\bsvg\s+(path|circle|ellipse|line|polyline|polygon|rect)\s*$/i;

// Same order as the browser applies them: the @import order of index.css (equal-specificity rules cascade by order).
const files = [...readFileSync(path.join(STYLES, 'index.css'), 'utf8').matchAll(/@import\s+['"]\.\/([^'"]+)['"]/g)]
  .map((m) => path.join(STYLES, m[1]))
  .filter((f) => f !== OUT && !f.includes(`${path.sep}vendor${path.sep}`) && readdirSync(path.dirname(f)).includes(path.basename(f)));

/** Walks one stylesheet, calling `onRule(atRules, selector, body)` for each style rule. */
function walk(css, onRule) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const stack = [];
  let buffer = '';
  for (const ch of css) {
    if (ch === '{') {
      stack.push({ prelude: buffer.trim(), body: '' });
      buffer = '';
    } else if (ch === '}') {
      const top = stack.pop();
      if (!top) continue;
      if (!top.prelude.startsWith('@')) {
        onRule(stack.map((s) => s.prelude).filter((p) => p.startsWith('@')), top.prelude, top.body + buffer);
      }
      buffer = '';
    } else if (stack.length && !stack[stack.length - 1].prelude.startsWith('@')) {
      stack[stack.length - 1].body += ch;
    } else {
      buffer += ch;
    }
  }
}

const entries = []; // { key: at-rule chain, rule } in stylesheet order
let count = 0;
for (const file of files) {
  walk(readFileSync(file, 'utf8'), (atRules, selector, body) => {
    if (atRules.some((a) => /^@(font-face|keyframes|-webkit-keyframes)/i.test(a))) return;
    const fill = body.split(';').map((d) => d.trim()).find((d) => /^fill\s*:/i.test(d));
    if (!fill) return;
    const value = fill.replace(/^fill\s*:\s*/i, '').trim();
    if (!value || /^(none|url\()/i.test(value)) return;
    const selectors = selector
      .split(',')
      .map((s) => s.trim())
      .filter((s) => SHAPE.test(s))
      .map((s) => `${s}.cms-stroke`);
    if (!selectors.length) return;
    entries.push({ key: atRules.join(' | '), rule: `${selectors.join(',\n')} { stroke: ${value} }` });
    count++;
  });
}

let out = `/*
 * GENERATED by scripts/generate-cms-stroke-css.mjs, do not edit by hand.
 * Outline icons (class "cms-stroke", set by sanitizeSvg) take the colour of every icon \`fill\` rule on their \`stroke\`.
 */
.cms-svg svg .cms-stroke.cms-stroke { fill: none !important }
.cms-svg svg .cms-stroke { transition: stroke .3s ease-in-out }

`;
// Consecutive rules with the same @media chain share one block, but the order is never changed.
const blocks = [];
for (const { key, rule } of entries) {
  const last = blocks[blocks.length - 1];
  if (last && last.key === key) last.rules.push(rule);
  else blocks.push({ key, rules: [rule] });
}
for (const { key, rules } of blocks) {
  const body = rules.join('\n');
  if (!key) out += `${body}\n\n`;
  else {
    const chain = key.split(' | ');
    out += `${chain.map((a, i) => `${'  '.repeat(i)}${a} {`).join('\n')}\n${body.split('\n').map((l) => '  '.repeat(chain.length) + l).join('\n')}\n${chain.map((_, i) => `${'  '.repeat(chain.length - 1 - i)}}`).join('\n')}\n\n`;
  }
}
writeFileSync(OUT, out);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${count} icon fill rules mirrored onto stroke`);
